/** A word nobody has drawn yet in this match. */
export function pickDrawWord(used: string[]): string {
  const taken = new Set(used.map((w) => w.toLowerCase()));
  const pool = DRAW_WORDS.filter((w) => !taken.has(w.toLowerCase()));
  const list = pool.length > 0 ? pool : DRAW_WORDS;
  return list[Math.floor(Math.random() * list.length)]!;
}
